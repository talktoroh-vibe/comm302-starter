// Helper to generate realistic chart points around a base price
function generateChartSeries(basePrice: number, pointsCount: number, volatility = 0.015, trend = 0.005) {
  const points = [];
  let currentPrice = basePrice * (1 - trend);
  const now = new Date('2026-09-28T09:30:00');

  for (let i = 0; i < pointsCount; i++) {
    const timeDelta = i * (390 / pointsCount); // minutes into trading day
    const time = new Date(now.getTime() + timeDelta * 60 * 1000);
    const timeStr = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });

    const change = currentPrice * (Math.random() * volatility * 2 - volatility + trend / pointsCount);
    currentPrice = Math.max(currentPrice * 0.5, currentPrice + change);

    const open = currentPrice;
    const high = open * (1 + Math.random() * 0.004);
    const low = open * (1 - Math.random() * 0.004);
    const close = low + Math.random() * (high - low);

    points.push({
      time: timeStr,
      price: Number(close.toFixed(2)),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume: Math.floor(Math.random() * 500000 + 100000),
    });
  }
  return points;
}

